const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/*',route=>route.request().url().startsWith('http://127.0.0.1:8766/')?route.continue():route.abort());
 await page.goto('http://127.0.0.1:8766/cf-dash/#cooking');
 await page.evaluate(()=>{setGate(false);go('cooking');});
 assert.equal(await page.locator('.ck-day').count(),7);
 assert.equal(await page.locator('#ck-composer').isVisible(),false);
 const count=await page.evaluate(()=>recipes().length);
 await page.getByRole('button',{name:'High protein',exact:true}).click();
 await page.locator('.ck-recipe').first().getByRole('button',{name:'View recipe',exact:true}).click();
 assert.equal(await page.evaluate(()=>recipes().length),count,'browsing must not add a copy');
 await page.locator('#ck-detail').getByRole('button',{name:'Close',exact:true}).click();
 await page.getByRole('button',{name:'Add a recipe',exact:true}).click();
 await page.locator('#ck-title').fill('Test curry');await page.locator('#ck-ingredients').fill('200 g chicken\n1 onion');await page.locator('#ck-steps').fill('Soften onion\nCook chicken');
 await page.getByRole('button',{name:'Save recipe',exact:true}).click();
 await page.getByRole('button',{name:'All recipes',exact:true}).click();
 const recipe=page.locator('.ck-recipe').filter({hasText:'Test curry'});
 const date=await page.evaluate(()=>ckKeyDate(new Date()));
 await recipe.locator('select').selectOption(date);
 assert.equal(await page.locator('.ck-next h4').textContent(),'Test curry');
 await page.locator('.ck-next > .ck-check').first().locator('input').check();
 
 assert.equal(await page.locator('.ck-shopping .ck-check').count(),1,'pantry items omitted');
 await page.locator('.ck-shopping .ck-check input').check();
 await page.reload();await page.evaluate(()=>{setGate(false);go('cooking');});
 assert.equal(await page.locator('.ck-next > .ck-check input').first().isChecked(),true);
 assert.equal(await page.locator('.ck-shopping .ck-check input').isChecked(),true);
 await page.locator('.ck-meal').click();
 const tomorrow=await page.evaluate(()=>{const d=new Date();d.setDate(d.getDate()+1);return ckKeyDate(d);});
 await page.locator('#ck-detail input[type=date]').fill(tomorrow);
 assert.equal(await page.evaluate(()=>ckPlan()[0].date),tomorrow);
 await page.locator('#ck-detail').getByRole('button',{name:'Close',exact:true}).click();
 await page.locator('.ck-next').getByRole('button',{name:'Cooked it',exact:true}).click();
 assert.equal(await page.evaluate(()=>ckPlan()[0].done),true);
 await page.getByRole('button',{name:'Add a recipe',exact:true}).click();
 await page.locator('#ck-title').fill('Unsafe link');await page.locator('#ck-link').fill('javascript:alert(1)');await page.getByRole('button',{name:'Save recipe',exact:true}).click();
 assert.match(await page.locator('#ck-status').textContent(),/http or https/);
 await page.locator('#ck-composer').getByRole('button',{name:'Close',exact:true}).click();
 await page.screenshot({path:'../cooking-sources/cooking-desktop.png',fullPage:true});
 const rect=await page.locator('.wrap').boundingBox();assert.ok(rect.width>1200,'desktop uses available width');
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile must not overflow');
 await page.screenshot({path:'../cooking-sources/cooking-mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('PASS: calendar, no-copy protein browsing, recipe save, planning, pantry, bought persistence, move, cooked, URL validation, desktop width, mobile overflow');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
